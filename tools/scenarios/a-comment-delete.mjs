import { BASE, accessToken } from '../lib.mjs';
import { newBrowser, newPage } from './a-lib.mjs';
const tok = await accessToken('kam');
const H = { Authorization: `Bearer ${tok}`, 'Content-Type': 'application/json' };
const deal = (await (await fetch(`${BASE}/api/deals?q=D-2026-000002&limit=1`, { headers: H })).json()).items[0];
await fetch(`${BASE}/api/deals/${deal.id}/comments`, { method: 'POST', headers: H, body: JSON.stringify({ body: 'Удалить меня' }) });
const browser = await newBrowser();
const page = await newPage(browser, { who: 'kam' });
page.on('response', (r) => r.request().method() === 'DELETE' && console.log('DELETE', r.status(), r.url().replace(BASE, '')));
await page.goto(`${BASE}/deals/${deal.id}?tab=comments`, { waitUntil: 'load' });
const item = page.locator('[data-comment]', { hasText: 'Удалить меня' }).last();
await item.waitFor();
await item.hover();
await item.getByRole('button', { name: 'Удалить' }).click();
await page.waitForTimeout(600);
console.log('диалог:', JSON.stringify(await page.locator('.atmr-modal-wrapper').allInnerTexts()));
await page.screenshot({ path: '.shots/a/comment-delete.png' });
await page.locator('.atmr-modal-wrapper').getByRole('button', { name: 'Удалить' }).click();
await page.waitForTimeout(1200);
console.log('осталось:', await page.locator('[data-comment]', { hasText: 'Удалить меня' }).count());
console.log('problems', JSON.stringify(page.__problems));
await browser.close();
