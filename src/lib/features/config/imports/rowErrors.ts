// Замечания строк проверки импорта: тексты сервера понятны, но не говорят, что делать. Здесь к известным текстам добавляется «чем исправить»
// (и ссылка, если исправление — в другом разделе). Правила привязаны к текстам бэкенда (`imports/service.py`, `imports/fields.py`,
// `catalog/license_values.py`); неизвестный текст остаётся как есть.

export interface RowRemark {
	text: string;
	fix?: string;
	link?: { label: string; href: string };
}

const STATUS_FIX = 'Допустимо: передано, в работе, не начато, отказ (или not_started, in_progress, transferred, declined).';

const RULES: { test: RegExp; explain: (text: string) => Omit<RowRemark, 'text'> }[] = [
	{
		test: /^«Название ВУЗа»: значение .+ не найдено$/s,
		explain: () => ({ fix: 'Вуз ищется по точному названию в справочнике организаций. Проверьте написание или заведите организацию.', link: { label: 'Организации', href: '/organizations' } })
	},
	{
		test: /^«[^»]+»: значение .+ не найдено$/s,
		explain: () => ({ fix: 'Значение ищется в справочнике по точному совпадению. Проверьте написание в файле.' })
	},
	{ test: /Номер договора уже относится к другой организации/, explain: () => ({ fix: 'Этот номер договора уже есть у другого вуза. Проверьте номер или название вуза в строке.' }) },
	{ test: /^Запись для обновления не найдена$/, explain: () => ({ fix: 'В режиме «Только обновить» запись должна уже существовать. Выберите «Создать и обновить» или проверьте вуз, вендора, ПО и номер договора.' }) },
	{ test: /^Пропущена при применении: уже существует$/, explain: () => ({ fix: 'Такая запись уже есть, а режим «Только создать» её не меняет. Выберите «Создать и обновить», чтобы обновить.' }) },
	{ test: /^«Статус по передаче»|статус по передаче/i, explain: () => ({ fix: STATUS_FIX }) },
	{ test: /«Подписание лицензии».*не распознано/s, explain: () => ({ fix: 'Допустимо: да, нет или дата подписания (ДД.ММ.ГГГГ).' }) },
	{ test: /срок действия не распознан/, explain: () => ({ fix: 'Допустимо: год окончания (например 2027), срок в годах (3 или «3 года») или «бессрочно».' }) },
	{ test: /нераспознанный формат даты/, explain: () => ({ fix: 'Допустимо: ДД.ММ.ГГГГ или ГГГГ-ММ-ДД.' }) }
];

/** Замечание с подсказкой «что делать», если текст известен. */
function explainRowError(text: string): RowRemark {
	for (const rule of RULES) if (rule.test.test(text)) return { text, ...rule.explain(text) };
	return { text };
}

/** Все замечания строки; пустой список — пустой результат. */
export const explainRowErrors = (errors: readonly string[] | null | undefined): RowRemark[] => (errors ?? []).map(explainRowError);
